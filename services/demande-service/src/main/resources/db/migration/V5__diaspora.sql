-- Diaspora (modèle de la version 1) : zones de compétence, pays, types de mission, missions diplomatiques et leurs
-- villes. Un document papier peut être retiré à la mission compétente pour le pays de résidence.
CREATE TABLE zone_competence (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom         VARCHAR(150) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE pays (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id   BIGINT REFERENCES zone_competence (id),
    nom       VARCHAR(150) NOT NULL UNIQUE,
    code_iso  VARCHAR(3)   NOT NULL UNIQUE,
    continent VARCHAR(50),
    capitale  VARCHAR(100)
);

CREATE TABLE type_mission (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE mission_diplomatique (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id     BIGINT       NOT NULL REFERENCES type_mission (id),
    nom         VARCHAR(200) NOT NULL,
    pays_id     BIGINT       NOT NULL REFERENCES pays (id),
    ville       VARCHAR(150) NOT NULL,
    code_postal VARCHAR(20),
    competence  VARCHAR(255),
    adresse     VARCHAR(255) NOT NULL,
    telephone   VARCHAR(50),
    email       VARCHAR(150),
    active      BOOLEAN      NOT NULL DEFAULT TRUE
);

-- pays couverts par chaque mission (une ambassade peut couvrir plusieurs pays)
CREATE TABLE mission_pays (
    mission_id BIGINT NOT NULL REFERENCES mission_diplomatique (id),
    pays_id    BIGINT NOT NULL REFERENCES pays (id),
    PRIMARY KEY (mission_id, pays_id)
);

