CREATE TABLE type_document (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(40)  NOT NULL UNIQUE,
    libelle         VARCHAR(150) NOT NULL,
    description     VARCHAR(500),
    type_acte       VARCHAR(20)  NOT NULL,
    copie_integrale BOOLEAN      NOT NULL DEFAULT FALSE,
    tarif           INTEGER      NOT NULL,
    delai_jours     INTEGER      NOT NULL,
    actif           BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE motif (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle         VARCHAR(150) NOT NULL UNIQUE,
    ordre           INTEGER      NOT NULL
);

CREATE TABLE demande (
    id                  UUID         PRIMARY KEY,
    reference           VARCHAR(30)  NOT NULL UNIQUE,
    demandeur_id        VARCHAR(64)  NOT NULL,
    demandeur_email     VARCHAR(150) NOT NULL,
    demandeur_prenom    VARCHAR(150) NOT NULL,
    demandeur_nom       VARCHAR(100) NOT NULL,
    type_document_id    BIGINT       NOT NULL REFERENCES type_document(id),
    libelle_document    VARCHAR(150) NOT NULL,
    type_acte           VARCHAR(20)  NOT NULL,
    copie_integrale     BOOLEAN      NOT NULL,
    montant             INTEGER      NOT NULL,
    motif_id            BIGINT       REFERENCES motif(id),
    libelle_motif       VARCHAR(255),
    lien                VARCHAR(20)  NOT NULL,
    format              VARCHAR(20)  NOT NULL,
    adresse_livraison   VARCHAR(255),
    ville_livraison     VARCHAR(100),
    nom                 VARCHAR(100) NOT NULL,
    prenom              VARCHAR(150) NOT NULL,
    sexe                VARCHAR(1),
    date_naissance      DATE,
    lieu_naissance      VARCHAR(150),
    nom_pere            VARCHAR(100),
    prenom_pere         VARCHAR(150),
    nom_mere            VARCHAR(100),
    prenom_mere         VARCHAR(150),
    nom_conjoint        VARCHAR(100),
    prenom_conjoint     VARCHAR(150),
    date_evenement      DATE,
    statut              VARCHAR(30)  NOT NULL,
    acte_id             UUID,
    numero_acte         VARCHAR(40),
    note_recherche      VARCHAR(500),
    signataire          VARCHAR(150),
    date_signature      TIMESTAMP,
    code_verification   VARCHAR(20),
    motif_rejet         VARCHAR(500),
    date_creation       TIMESTAMP    NOT NULL,
    date_modification   TIMESTAMP    NOT NULL,
    version             INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX idx_demande_statut ON demande (statut, type_acte);
CREATE INDEX idx_demande_demandeur ON demande (demandeur_id);

CREATE TABLE historique_statut (
    id              UUID         PRIMARY KEY,
    demande_id      UUID         NOT NULL REFERENCES demande(id),
    ancien_statut   VARCHAR(30),
    nouveau_statut  VARCHAR(30)  NOT NULL,
    auteur          VARCHAR(200) NOT NULL,
    commentaire     VARCHAR(500),
    date_changement TIMESTAMP    NOT NULL
);
CREATE INDEX idx_historique_demande ON historique_statut (demande_id);

CREATE TABLE compteur_reference (
    annee           INTEGER PRIMARY KEY,
    dernier_numero  BIGINT  NOT NULL
);
