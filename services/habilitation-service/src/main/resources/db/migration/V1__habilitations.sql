-- Journal des opérations d'administration (ajout seul : aucune ligne n'est modifiée ni supprimée)
CREATE TABLE operation (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date    TIMESTAMP     NOT NULL,
    auteur  VARCHAR(250)  NOT NULL,
    type    VARCHAR(40)   NOT NULL,
    cible   VARCHAR(250)  NOT NULL,
    detail  VARCHAR(1000)
);
CREATE INDEX idx_operation_date ON operation (date DESC);
CREATE INDEX idx_operation_cible ON operation (cible);

-- Étapes d'initialisation déjà appliquées à l'annuaire
CREATE TABLE initialisation (
    etape   VARCHAR(80)  PRIMARY KEY,
    date    TIMESTAMP    NOT NULL
);
